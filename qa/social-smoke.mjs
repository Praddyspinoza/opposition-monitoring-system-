import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const html=readFileSync('index.html','utf8');
const match=html.match(/<script id="cgSocialSeed" type="application\/json">([\s\S]*?)<\/script>/);
assert(match,'social intelligence seed must be inline and usable offline');
const seed=JSON.parse(match[1]);
assert.equal(seed.x_accounts.length,10,'ten X account identity slots');
assert.equal(seed.x_posts.length,11,'eleven publisher-corroborated X status URLs');
assert(seed.press_leads.length>=14,'press-attributed social coverage');
assert(seed.x_posts.every(r=>/^https:\/\/x\.com\/[\w]+\/status\/\d+$/.test(r.url)),'all original X permalinks properly formatted');
assert.equal(new Set(seed.x_posts.map(r=>r.url)).size,seed.x_posts.length,'X status links unique');
assert(seed.press_leads.every(r=>r.url.startsWith('https://')),'all press source URLs present');
const errors=[];
const dom=new JSDOM(html,{url:'https://example.org/opposition-monitoring-system-/',runScripts:'dangerously',pretendToBeVisual:true,
 beforeParse(w){w.scrollTo=()=>{};w.Element.prototype.scrollIntoView=()=>{};w.matchMedia=()=>({matches:false,addListener(){},removeListener(){}});w.confirm=()=>true;w.addEventListener('error',e=>errors.push(String(e.message||e.error)));}
});
const {document,MouseEvent,Event}=dom.window;
const E=id=>document.getElementById(id);
document.querySelector('[data-nav="meta"]').dispatchEvent(new MouseEvent('click',{bubbles:true,cancelable:true}));
assert(document.getElementById('meta').classList.contains('active'));
assert.equal(E('siXCount').textContent,'11');
assert.equal(E('siPressCount').textContent,String(seed.press_leads.length));
assert.equal(E('siMetaCount').textContent,'0');
assert.equal(document.querySelectorAll('#siAccountDirectory .si-account').length,10,'10 account dossiers');
assert.equal(document.querySelectorAll('#siAccountDirectory .si-acc-platforms>div').length,30,'30 social profile slots');
assert.equal(document.querySelectorAll('#siLeader option').length,11,'all leader filters');
assert.equal(document.querySelectorAll('#siTopic option').length,6,'all five categories');
assert.equal(E('siMatches').textContent,'25 evidence items','all evidence cards counted');
E('siKind').value='x';E('siKind').dispatchEvent(new Event('change',{bubbles:true}));
assert.equal(E('siMatches').textContent,'11 evidence items','X filter counts original permalinks only');
assert.equal(document.querySelectorAll('#siEvidenceList .si-card a[href^="https://x.com/"]').length,11,'X links open original statuses');
E('siLeader').value='Deepak Baij';E('siLeader').dispatchEvent(new Event('change',{bubbles:true}));
assert.equal(E('siMatches').textContent,'2 evidence items','Deepak Baij original statuses');
E('siTopic').value='Tribal Issues';E('siTopic').dispatchEvent(new Event('change',{bubbles:true}));
assert.equal(E('siMatches').textContent,'2 evidence items','tribal topic tags normalized');
E('siFrom').value='2026-09-01';E('siFrom').dispatchEvent(new Event('change',{bubbles:true}));
assert.equal(E('siMatches').textContent,'0 evidence items','date filter works');
E('siReset').click();
assert.equal(E('siMatches').textContent,'25 evidence items','reset restores sources');
E('siKind').value='meta';E('siKind').dispatchEvent(new Event('change',{bubbles:true}));
assert.equal(E('siMatches').textContent,'1 evidence item','Facebook press reference but no fake Instagram posts');
assert.match(E('siEvidenceList').textContent,/not a retrieved first-party social post/i);
assert.equal(E('metaOriginalCount').textContent,'0','original Facebook/Instagram corpus remains empty');
assert.equal(errors.length,0,'No inline JavaScript errors: '+errors.join('; '));
console.log('PASS: cross-platform social evidence, original X URLs, 10×3 account slots, accurate Meta gaps, dates, five-topic filters');
